// Custom random-name pools for nations.
//
// In game every unit gets a random name from its nation's pool (TUnitNameNationToDicoToken in
// Gameplay/Gfx/UnitNames). A pool is a localisation dictionary registered in
// Gameplay/Gfx/UnitNamesDico (TLocalisationDicoResource -> CSV). Vanilla pools are plain numbered
// lists: tokens "1".."761" -> one name each (decoded from UNITNAMES_US.dic), so ours are too.

import { csvEscape } from "./ndf.js";

/** Value of nation.unitNamesDico meaning "use nation.customNames". */
export const CUSTOM_NAMES = "custom";
export const MIN_NAMES = 20; // fewer works, but repeats quickly
export const MAX_NAMES = 3000;
export const MAX_NAME_LENGTH = 28;

/**
 * Pasted text -> names. One per line; a single line of comma-separated names also works.
 * Blank lines and lines starting with # are skipped, duplicates (any case) dropped.
 * Returns { names, duplicates, tooLong, cleaned }.
 */
export function parseNameList(text = "") {
  const lines = String(text).split(/\r?\n/).filter((l) => l.trim() && !/^\s*#/.test(l));
  const parts = lines.length === 1 && /[,;\t]/.test(lines[0]) ? lines[0].split(/[,;\t]/) : lines;
  const seen = new Set();
  const names = [];
  let duplicates = 0;
  let cleaned = 0;
  for (const raw of parts) {
    // strip list bullets / numbering ("1. ", "- ", "* "), wrapping quotes and characters the CSV can't hold
    let name = raw
      .replace(/^\s*(?:[-*•]|\d+[.)])\s+/, "")
      .replace(/^["'`]+|["'`]+$/g, "")
      .replace(/[\p{Cc}";]/gu, "")
      .replace(/\s+/g, " ")
      .trim();
    if (name !== raw.trim()) cleaned++;
    if (!name) continue;
    if (name.length > 60) name = name.slice(0, 60);
    const key = name.toLowerCase();
    if (seen.has(key)) {
      duplicates++;
      continue;
    }
    seen.add(key);
    names.push(name);
  }
  return { names, duplicates, cleaned, tooLong: names.filter((n) => n.length > MAX_NAME_LENGTH) };
}

/**
 * Dictionary token for a nation's custom pool. The engine caps TLocalisationToken at 10 characters
 * (vanilla: "NAMES_USSR"), so "WRN_" + a tag of up to 6.
 */
export const namesDicoToken = (tag) => `WRN_${tag}`;

/** The pool CSV: "TOKEN";"REFTEXT" header, then "1";"Name" … like vanilla (CRLF). */
export function namesCsv(names) {
  return ['"TOKEN";"REFTEXT"', ...names.map((n, i) => `"${i + 1}";"${csvEscape(n)}"`)].join("\r\n") + "\r\n";
}

/** Registration file for Gameplay/Gfx/UnitNamesDico. */
export function namesDicoNdf(token, csvPath) {
  return `// Generated by Waranon\n\nunnamed TLocalisationDicoResource\n(\n    DicoToken = "${token}"\n    FileName = "GameData:/${csvPath.replace(/^GameData\//, "")}"\n)\n`;
}
